"""Where each Fear & Hunger body part sits on its monster, for Anki Hunger's real dismemberment.

The game ships monsters as a torso (same canvas as the whole sprite, stumps painted in) plus loose parts on padded
canvases, and the positions live in game data we don't have. This finds each part inside the whole sprite (masked
sum of squared differences, via FFT) and prints the MONSTERS entries for index.html. Assets stay private:
  python parts.py [C:\\dojo\\state\\fh-assets\\enemies] [C:\\dojo\\state\\abyss\\sprites] [--sheet out_dir]
"""
