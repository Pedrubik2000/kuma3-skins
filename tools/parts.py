def load(p):
    return np.asarray(Image.open(p).convert("RGBA")).astype(np.float32) / 255


def crop(a):
    ys, xs = np.nonzero(a[..., 3] > .5)
    return a[ys.min():ys.max() + 1, xs.min():xs.max() + 1]


def find(whole, part):
    """Top-left (x, y) of part in whole (part may hang off the edge) and the mean error there."""
    h, w = part.shape[:2]
    big = np.zeros((whole.shape[0] + 2 * h, whole.shape[1] + 2 * w, 4), np.float32)
    big[h:h + whole.shape[0], w:w + whole.shape[1]] = whole
    m = (part[..., 3] > .5).astype(np.float32)
    shape = big.shape[:2]
    F = lambda a: np.fft.rfft2(a, shape)
    corr = lambda a, k: np.fft.irfft2(F(a) * np.conj(F(k)), shape)
    ssd = sum(corr(big[..., c] ** 2, m) - 2 * corr(big[..., c], m * part[..., c]) for c in range(4))
    ssd = ssd[:shape[0] - h + 1, :shape[1] - w + 1]   # only offsets where the part fits in the padded image
    y, x = np.unravel_index(np.argmin(ssd), ssd.shape)
    err = float(np.abs(big[y:y + h, x:x + w] - part)[m > 0].mean())
    return int(x) - w, int(y) - h, err


def main():
    args, sheet = sys.argv[1:], None
    if "--sheet" in args:
        i = args.index("--sheet"); sheet = Path(args[i + 1]); del args[i:i + 2]
    parts_dir = Path(args[0] if args else r"C:\dojo\state\fh-assets\enemies")
    whole_dir = Path(args[1] if len(args) > 1 else r"C:\dojo\state\abyss\sprites")
    print("const PARTS = {   // generated by parts.py: [file, kind, x, y, w, h, visible box x, y, w, h, baked into the torso]")
    for name, (prefix, kinds) in SETS.items():
        whole_png = whole_dir / f"{name}.png" if (whole_dir / f"{name}.png").exists() else parts_dir / f"{name}.png"
        whole = load(whole_png)
        out = []
        for suffixes, kind in kinds.items():
            best = None
            for f in (f"{prefix}{s}" for s in suffixes.split("|")):
                raw = load(parts_dir / f"{f}.png")
                ys, xs = np.nonzero(raw[..., 3] > .5)
                x, y, err = find(whole, crop(raw))
                if not best or err < best[-1]:   # x, y: back to the padded canvas's corner
                    best = (f, kind, x - int(xs.min()), y - int(ys.min()), raw, err)
            out.append(best)
            print(f"  {best[0]:28} {kind:5} at {best[2]:5},{best[3]:5}  err {best[-1]:.3f}", file=sys.stderr)
        tf, _, tx, ty, torso, _ = next((o for o in out if o[1] == "torso"), (None, None, 0, 0, None, None))
        rows = []
        for f, kind, x, y, raw, _ in out:
            ys, xs = np.nonzero(raw[..., 3] > .5)
            baked = 0   # the game never cuts legs, so their pixels are painted into the torso too: erase them on a cut
            if kind != "torso" and torso is not None:
                a, b = ys + y - ty, xs + x - tx
                ok = (a >= 0) & (a < torso.shape[0]) & (b >= 0) & (b < torso.shape[1])
                same = np.abs(torso[a[ok], b[ok]] - raw[ys[ok], xs[ok]]).max(-1) < .05
                baked = int(same.sum() / len(ys) > .4)
            rows.append(f'["{f}","{kind}",{x},{y},{raw.shape[1]},{raw.shape[0]},{x + xs.min()},{y + ys.min()},{xs.max() - xs.min() + 1},{ys.max() - ys.min() + 1},{baked}]')
        print(f'  {name}: [{",".join(rows)}],')
        if sheet:   # whole | rebuilt from parts, to check by eye
            H, W = whole.shape[:2]
            img = Image.new("RGBA", (W * 2, H), (34, 34, 34, 255))
            img.alpha_composite(Image.open(whole_png).convert("RGBA"))
            canvas = Image.new("RGBA", (W, H))
            for f, k, x, y, *_ in out:
                p = Image.open(parts_dir / f"{f}.png").convert("RGBA")
                layer = Image.new("RGBA", (W, H)); layer.paste(p, (x, y)); canvas = Image.alpha_composite(canvas, layer)
            img.alpha_composite(canvas, (W, 0))
            sheet.mkdir(parents=True, exist_ok=True)
            img.save(sheet / f"{name}.png")
    print("};")


if __name__ == "__main__":
    main()
